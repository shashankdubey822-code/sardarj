CREATE TABLE IF NOT EXISTS public.institutional_rfqs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_ref VARCHAR(40) UNIQUE NOT NULL,
    source_channel VARCHAR(32) NOT NULL DEFAULT 'website',
    institution_category VARCHAR(128) NOT NULL,
    institution_name VARCHAR(200) NOT NULL,
    contact_person VARCHAR(160) NOT NULL,
    phone VARCHAR(64) NOT NULL,
    email VARCHAR(160),
    city VARCHAR(160) DEFAULT 'Faridabad / Delhi NCR',
    total_quantity INT NOT NULL DEFAULT 150,
    discount_tier VARCHAR(160),
    queued_items JSONB NOT NULL DEFAULT '[]'::jsonb,
    customization_type VARCHAR(200),
    swatch_sample_needed BOOLEAN NOT NULL DEFAULT TRUE,
    requirement_notes TEXT,
    target_delivery_date VARCHAR(120),
    google_form_response_id VARCHAR(128),
    status VARCHAR(48) NOT NULL DEFAULT 'new',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_institutional_rfqs_created_at
    ON public.institutional_rfqs (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_institutional_rfqs_source
    ON public.institutional_rfqs (source_channel);

CREATE INDEX IF NOT EXISTS idx_institutional_rfqs_status
    ON public.institutional_rfqs (status);

ALTER TABLE public.institutional_rfqs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public RFQ submission" ON public.institutional_rfqs;
CREATE POLICY "Allow public RFQ submission"
    ON public.institutional_rfqs
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "Service role full access to institutional_rfqs" ON public.institutional_rfqs;
CREATE POLICY "Service role full access to institutional_rfqs"
    ON public.institutional_rfqs
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);
